#!/usr/bin/env node
/**
 * Converts a .docx whitepaper into the DocBlock shape the reader renders.
 *
 * Emits two artefacts from one parse, so the fixture and the database cannot
 * drift into telling different stories:
 *
 *   src/content/fixtures/atonomos.document.ts   — local dev
 *   supabase/migrations/<stamp>_atonomos_document.sql — every deployment
 *
 * Reads the XML directly rather than taking a dependency: a Word document is
 * a zip of XML, the subset that matters here is headings, paragraphs and list
 * items, and a converter would bring along a large surface for a job this
 * narrow.
 *
 * Usage: node scripts/import-whitepaper.mjs <path-to.docx>
 */
import fs from 'node:fs'
import path from 'node:path'
import zlib from 'node:zlib'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = process.argv[2]

if (!source || !fs.existsSync(source)) {
  console.error('✗ usage: node scripts/import-whitepaper.mjs <path-to.docx>')
  process.exit(1)
}

/**
 * Minimal zip reader — pulls one member out of the archive by name.
 *
 * Sizes come from the CENTRAL DIRECTORY, not the local file header. When a
 * writer streams an entry it sets the data-descriptor flag and leaves the
 * local header's sizes as zero, filling them in after the payload; trusting
 * them yields an empty body and an inflate error. Word writes this way.
 */
function readZipEntry(file, wanted) {
  const buf = fs.readFileSync(file)

  // End of central directory: fixed 22-byte record, possibly followed by a
  // comment, so scan back from the end for its signature.
  let eocd = -1
  for (let i = buf.length - 22; i >= 0; i--) {
    if (buf.readUInt32LE(i) === 0x06054b50) {
      eocd = i
      break
    }
  }
  if (eocd === -1) throw new Error(`${file} is not a zip archive`)

  const count = buf.readUInt16LE(eocd + 10)
  let p = buf.readUInt32LE(eocd + 16)

  for (let n = 0; n < count; n++) {
    if (buf.readUInt32LE(p) !== 0x02014b50) break
    const method = buf.readUInt16LE(p + 10)
    const compSize = buf.readUInt32LE(p + 20)
    const nameLen = buf.readUInt16LE(p + 28)
    const extraLen = buf.readUInt16LE(p + 30)
    const commentLen = buf.readUInt16LE(p + 32)
    const localOffset = buf.readUInt32LE(p + 42)
    const name = buf.subarray(p + 46, p + 46 + nameLen).toString('utf8')

    if (name === wanted) {
      // The local header's own name/extra lengths give where the data starts;
      // its extra field can differ in length from the central one.
      const lNameLen = buf.readUInt16LE(localOffset + 26)
      const lExtraLen = buf.readUInt16LE(localOffset + 28)
      const start = localOffset + 30 + lNameLen + lExtraLen
      const body = buf.subarray(start, start + compSize)
      return method === 0 ? body.toString('utf8') : zlib.inflateRawSync(body).toString('utf8')
    }
    p += 46 + nameLen + extraLen + commentLen
  }
  throw new Error(`${wanted} not found in ${file}`)
}

const xml = readZipEntry(source, 'word/document.xml')

const ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'" }
function decode(s) {
  return s
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&(amp|lt|gt|quot|apos);/g, (_, e) => ENTITIES[e])
}

function textOf(p) {
  // <w:tab/> and <w:br/> carry meaning; everything else outside <w:t> is markup.
  const withBreaks = p.replace(/<w:tab[^>]*\/>/g, ' ').replace(/<w:br[^>]*\/>/g, '\n')
  const runs = [...withBreaks.matchAll(/<w:t[^>]*>([\s\S]*?)<\/w:t>/g)].map((m) => m[1])
  return decode(runs.join('')).replace(/\s+/g, ' ').trim()
}

const paragraphs = [...xml.matchAll(/<w:p[ >][\s\S]*?<\/w:p>/g)].map((m) => m[0])

const raw = []
for (const p of paragraphs) {
  const text = textOf(p)
  if (!text) continue
  const style = /<w:pStyle w:val="([^"]+)"/.exec(p)?.[1] ?? ''
  const heading = /^Heading(\d)$/.exec(style)
  if (heading) {
    raw.push({ kind: 'h', level: Math.min(Number(heading[1]), 3), text })
  } else if (p.includes('<w:numPr>')) {
    raw.push({ kind: 'li', text })
  } else {
    raw.push({ kind: 'p', text })
  }
}

// Consecutive list items become one block, so the reader emits a single <ul>
// rather than a run of one-item lists.
const blocks = []
for (const block of raw) {
  const last = blocks[blocks.length - 1]
  if (block.kind === 'li' && last?.kind === 'ul') last.items.push(block.text)
  else if (block.kind === 'li') blocks.push({ kind: 'ul', items: [block.text] })
  else blocks.push(block)
}

const words = blocks.reduce(
  (n, b) => n + (b.kind === 'ul' ? b.items.join(' ') : b.text).split(/\s+/).length,
  0,
)

// ── Fixture ──────────────────────────────────────────────────────────────
const fixturePath = path.join(root, 'src/content/fixtures/atonomos.document.ts')
fs.writeFileSync(
  fixturePath,
  `// AUTO-GENERATED by scripts/import-whitepaper.mjs — do not edit by hand.
// Source: ${path.basename(source)}
// Regenerate: node scripts/import-whitepaper.mjs <path-to.docx>

import type { DocBlock } from '@/content/types'

export const atonomosDocument: DocBlock[] = ${JSON.stringify(blocks, null, 2)}
`,
)

// ── Migration ────────────────────────────────────────────────────────────
// Carried as data so every environment gets the paper through `db push`,
// matching how the bio is seeded. The body is one jsonb literal; Postgres
// dollar-quoting avoids escaping the prose's own quotes and apostrophes.
const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14)
const migrationPath = path.join(root, `supabase/migrations/${stamp}_atonomos_document.sql`)
fs.writeFileSync(
  migrationPath,
  `-- The Atonomos whitepaper body. AUTO-GENERATED by scripts/import-whitepaper.mjs.
--
-- Stored as jsonb blocks rather than HTML or a file: the reader renders
-- semantic blocks with the app's own typography, and nothing arrives as
-- markup that would need sanitising before display.

alter table content add column if not exists document jsonb;

comment on column content.document is
  'DocBlock[] for ereader content — headings, paragraphs and lists in reading order.';

update content ct
set document = $doc$${JSON.stringify(blocks)}$doc$::jsonb
from projects p, creators c
where ct.project_id = p.id
  and p.owner_creator_id = c.id
  and c.slug = 'dean'
  and p.slug = 'atonomos'
  and ct.type = 'ereader';
`,
)

const counts = blocks.reduce((acc, b) => ({ ...acc, [b.kind]: (acc[b.kind] ?? 0) + 1 }), {})
console.log(`✓ ${blocks.length} blocks (${JSON.stringify(counts)}), ~${words} words`)
console.log(`  → ${path.relative(root, fixturePath)}`)
console.log(`  → ${path.relative(root, migrationPath)}`)
