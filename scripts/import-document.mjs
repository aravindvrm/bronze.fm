#!/usr/bin/env node
/**
 * Converts a document into the DocBlock shape the reader renders.
 *
 * Replaces import-whitepaper.mjs, which read .docx and nothing else. Four
 * formats now, all landing in the same block model:
 *
 *   .docx            Word XML, read directly — scripts/parsers/docx.mjs
 *   .md / .markdown  through `marked` to HTML, then the HTML mapper
 *   .html / .htm     the HTML mapper
 *   .txt             blank-line-separated paragraphs
 *
 * Markdown goes through a converter where the reader's own pagination did
 * not, and the difference is worth naming: CommonMark plus GFM is a real
 * specification with a hundred edge cases, `marked` implements it, and this
 * runs at BUILD time so it costs the shipped bundle nothing. Pagination was
 * the opposite case — the libraries on offer solved a different problem
 * (rendering packaged EPUBs) and would have shipped to every visitor.
 *
 * Emits two artefacts from one parse, so the fixture and the database cannot
 * drift into telling different stories:
 *
 *   src/content/fixtures/<slug>.document.ts   — local dev
 *   supabase/migrations/<stamp>_<slug>_document.sql — every deployment
 *
 * Usage: node scripts/import-document.mjs <file> [--slug atonomos]
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { marked } from 'marked'
import { htmlToBlocks } from './parsers/html.mjs'
import { docxToBlocks } from './parsers/docx.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const args = process.argv.slice(2)
const source = args.find((a) => !a.startsWith('--'))
const slug = args.includes('--slug') ? args[args.indexOf('--slug') + 1] : 'atonomos'

if (!source || !fs.existsSync(source)) {
  console.error(
    '✗ usage: node scripts/import-document.mjs <file.docx|.md|.html|.txt> [--slug atonomos]',
  )
  process.exit(1)
}

/**
 * Plain text: a blank line starts a new paragraph.
 *
 * Nothing is inferred beyond that — no treating an ALL-CAPS line as a
 * heading, no reading `- ` as a list. A .txt file has no structure by
 * definition, and guessing at one produces a document that is wrong in ways
 * the author cannot see or correct.
 */
function textToBlocks(text) {
  return text
    .split(/\n\s*\n/)
    .map((para) => para.trim().replace(/\s+/g, ' '))
    .filter(Boolean)
    .map((para) => ({ kind: 'p', spans: [{ text: para }] }))
}

const ext = path.extname(source).toLowerCase()
let blocks
let images = 0

if (ext === '.docx') {
  ;({ blocks, images } = docxToBlocks(source))
} else if (ext === '.md' || ext === '.markdown') {
  blocks = htmlToBlocks(marked.parse(fs.readFileSync(source, 'utf8'), { async: false }))
} else if (ext === '.html' || ext === '.htm') {
  blocks = htmlToBlocks(fs.readFileSync(source, 'utf8'))
} else if (ext === '.txt') {
  blocks = textToBlocks(fs.readFileSync(source, 'utf8'))
} else {
  console.error(`✗ ${ext || 'that'} is not a format this reads — .docx, .md, .html or .txt`)
  process.exit(1)
}

if (!blocks.length) {
  console.error('✗ nothing readable in that file — no blocks produced')
  process.exit(1)
}

// Counted the same way the app counts, from the one shared helper, so the
// hub's read time and the reader's "min left" cannot disagree with this.
const words = blocks.reduce((n, b) => {
  const spans = (s) => (s ?? []).map((x) => x.text).join('')
  const text =
    b.kind === 'h' || b.kind === 'code'
      ? b.text
      : b.kind === 'ul' || b.kind === 'ol'
        ? b.items.map(spans).join(' ')
        : b.kind === 'table'
          ? [...(b.head ? [b.head] : []), ...b.rows]
              .map((r) => r.map((c) => spans(c.spans)).join(' '))
              .join(' ')
          : b.kind === 'figure'
            ? spans(b.caption)
            : b.kind === 'rule'
              ? ''
              : spans(b.spans)
  const trimmed = text.trim()
  return n + (trimmed ? trimmed.split(/\s+/).length : 0)
}, 0)

// ── Fixture ──────────────────────────────────────────────────────────────
const header = `// AUTO-GENERATED by scripts/import-document.mjs — do not edit by hand.
// Source: ${path.basename(source)}
// Regenerate: node scripts/import-document.mjs <file> --slug ${slug}
`

const fixturePath = path.join(root, `src/content/fixtures/${slug}.document.ts`)
fs.writeFileSync(
  fixturePath,
  `${header}
import type { DocBlock } from '@/content/types'

export const ${slug}Document: DocBlock[] = ${JSON.stringify(blocks, null, 2)}
`,
)

// ── Fixture meta ─────────────────────────────────────────────────────────
// Split from the prose above ON PURPOSE. The project hub only needs a read
// time, and importing the document to count its words would drag the whole
// paper into the initial bundle for every visitor, including everyone who
// never opens the reader.
fs.writeFileSync(
  path.join(root, `src/content/fixtures/${slug}.meta.ts`),
  `${header}
/** Words in ${slug}Document, for the hub's read-time estimate. */
export const ${slug}WordCount = ${words}
`,
)

// ── Migration ────────────────────────────────────────────────────────────
const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14)
const migrationPath = path.join(root, `supabase/migrations/${stamp}_${slug}_document.sql`)
fs.writeFileSync(
  migrationPath,
  `-- The ${slug} document body. AUTO-GENERATED by scripts/import-document.mjs.
--
-- Stored as jsonb blocks rather than HTML or a file: the reader renders
-- semantic blocks with the app's own typography, and nothing arrives as
-- markup that would need sanitising before display.

update content ct
set document = $doc$${JSON.stringify(blocks)}$doc$::jsonb
from projects p, creators c
where ct.project_id = p.id
  and p.owner_creator_id = c.id
  and c.slug = 'deanMaye'
  and p.slug = '${slug}'
  and ct.type = 'ereader';
`,
)

const counts = blocks.reduce((acc, b) => ({ ...acc, [b.kind]: (acc[b.kind] ?? 0) + 1 }), {})
console.log(`✓ ${blocks.length} blocks (${JSON.stringify(counts)}), ~${words} words`)
console.log(`  → ${path.relative(root, fixturePath)}`)
console.log(`  → ${path.relative(root, migrationPath)}`)

/*
 * Loud about what was lost, rather than silent.
 *
 * The old importer dropped every one of these without a word, which is how a
 * table could turn into scrambled prose and nobody find out. A count on
 * stderr is the difference between a known gap and a mystery.
 */
if (images) {
  console.error(
    `\n! ${images} embedded image${images === 1 ? '' : 's'} not imported.\n` +
      `  Word stores them inside the .docx; serving them needs somewhere to put them.\n` +
      `  Link them from the document, or raise it as its own piece of work.`,
  )
}
