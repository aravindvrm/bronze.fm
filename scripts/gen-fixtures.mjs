// Reads the local master audio and emits a typed fixture module.
//
// Durations come from macOS `afinfo`. This is a dev-time convenience only —
// in Phase 3 the ingest script writes the same shape into Supabase, hashing
// each file so its URL is content-addressed.
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { cleanTitle } from './lib/titles.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const audioDir = path.join(root, 'Bronze')
const outFile = path.join(root, 'src/content/fixtures/bronze.generated.ts')

function probe(file) {
  try {
    const out = execFileSync('afinfo', [file], { encoding: 'utf8' })
    const dur = out.match(/estimated duration:\s*([\d.]+)/)
    const fmt = out.match(/(\d+)\s*ch,\s*(\d+)\s*Hz/)
    const br = out.match(/bit rate:\s*(\d+)/)
    return {
      durationMs: dur ? Math.round(parseFloat(dur[1]) * 1000) : 0,
      channels: fmt ? Number(fmt[1]) : 2,
      sampleRate: fmt ? Number(fmt[2]) : 44100,
      bitrate: br ? Number(br[1]) : 0,
    }
  } catch {
    return { durationMs: 0, channels: 2, sampleRate: 44100, bitrate: 0 }
  }
}

// AppleDouble sidecars (._*) are not audio — exclude them.
const files = fs
  .readdirSync(audioDir)
  .filter((f) => /\.mp3$/i.test(f) && !f.startsWith('._'))
  .sort()

const items = files.map((f, i) => {
  const full = path.join(audioDir, f)
  const { durationMs, channels, sampleRate, bitrate } = probe(full)
  const hash = crypto.createHash('sha256').update(fs.readFileSync(full)).digest('hex').slice(0, 16)
  return {
    id: `itm_${String(i + 1).padStart(2, '0')}`,
    position: i + 1,
    title: cleanTitle(f),
    isInterlude: /\(skit\)/i.test(f),
    // Placeholder until Dean supplies real per-track credits. Interludes get
    // none; everything else is attributed to the owner.
    credits: /\(skit\)/i.test(f) ? [] : [{ creatorSlug: 'dean', name: 'Dean', role: 'artist' }],
    hash,
    bytes: fs.statSync(full).size,
    durationMs,
    channels,
    sampleRate,
    bitrate,
    url: `/media/audio/${encodeURIComponent(f)}`,
  }
})

const totalMs = items.reduce((a, t) => a + t.durationMs, 0)

const body = `// AUTO-GENERATED by scripts/gen-fixtures.mjs — do not edit by hand.
// Source: ./Bronze (gitignored, unmastered rough mixes).
// Regenerate: npm run fixtures

import type { Content, Creator, Project } from '@/content/types'
import deanAvatar from '@/assets/avatars/dean.jpg'

export const dean: Creator = {
  id: 'crt_dean',
  slug: 'dean',
  name: 'Dean',
  bio: 'Technology executive, venture investor, and strategic advisor with 15+ years leading enterprise transformation, AI innovation, and technology-enabled value creation across Fortune 500 enterprises, venture-backed and growth-staged businesses. Combines executive leadership, investment perspective, and deep technical expertise to accelerate business transformation and performance.',
  // Low-quality source photo, kept until Dean supplies a better one — see
  // src/assets/avatars/dean.jpg.
  avatarUrl: deanAvatar,
  // Mirrors the seed in 20260821020000_creator_profile.sql so fixtures and
  // Supabase render the same profile.
  socials: { linkedin: 'https://www.linkedin.com/in/odeanmaye/' },
  tier: 'standard',
  subdomain: null,
  customDomain: null,
}

export const bronzeMusic: Content = {
  id: 'cnt_bronze_music',
  type: 'music',
  ownerSlug: 'dean',
  projectSlug: 'bronze',
  title: 'Bronze',
  published: false,
  totalDurationMs: ${totalMs},
  credits: [{ creatorSlug: 'dean', name: 'Dean', role: 'artist' }],
  items: ${JSON.stringify(items, null, 2).replace(/\n/g, '\n  ')},
  // Mirrors this row's actual created_at in Supabase, so the feed orders
  // fixtures the same way it orders production.
  createdAt: '2026-08-21T02:37:28.615Z',
}

export const bronze: Project = {
  id: 'prj_bronze',
  ownerSlug: 'dean',
  slug: 'bronze',
  title: 'Bronze',
  published: false,
  contents: [bronzeMusic],
}
`

fs.mkdirSync(path.dirname(outFile), { recursive: true })
fs.writeFileSync(outFile, body)

// Sidecar for tooling that cannot import TypeScript — gen-test-audio.mjs
// (synthesises stand-in media in CI) and ingest.mjs (uploads to Supabase).
// Full item shape, not a trimmed one, so this stays the single source of
// truth for the tracklist rather than drifting into a second one.
fs.writeFileSync(
  path.join(path.dirname(outFile), 'bronze.manifest.json'),
  JSON.stringify(
    {
      creator: { slug: 'dean', name: 'Dean', tier: 'standard' },
      slug: 'bronze',
      type: 'music',
      title: 'Bronze',
      credits: [{ creatorSlug: 'dean', name: 'Dean', role: 'artist' }],
      totalDurationMs: totalMs,
      items,
    },
    null,
    2,
  ),
)
console.log(`✓ ${items.length} items → ${path.relative(root, outFile)}`)
console.log(
  `  total runtime ${Math.floor(totalMs / 60000)}m ${Math.round((totalMs % 60000) / 1000)}s`,
)
