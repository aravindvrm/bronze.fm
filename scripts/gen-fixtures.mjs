// Reads the local master audio and emits a typed fixture module.
//
// Durations come from macOS `afinfo`. This is a dev-time convenience only —
// in Phase 3 the ingest script writes the same shape into Supabase, hashing
// each file so its URL is content-addressed.
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const audioDir = path.join(root, 'Bronze')
const outFile = path.join(root, 'src/content/fixtures/bronze.generated.ts')

/** Strip the leading track number, restore apostrophes lost to filename escaping. */
function cleanTitle(filename) {
  return filename
    .replace(/\.mp3$/i, '')
    .replace(/^\d+\s*-\s*/, '')
    .replace(/_s\b/g, "'s")
    .replace(/\s+/g, ' ')
    .trim()
}

function probe(file) {
  try {
    const out = execFileSync('afinfo', [file], { encoding: 'utf8' })
    const dur = out.match(/estimated duration:\s*([\d.]+)/)
    const fmt = out.match(/(\d+)\s*ch,\s*(\d+)\s*Hz/)
    const br = out.match(/bit rate:\s*(\d+)/)
    return {
      durationMs: dur ? Math.round(parseFloat(dur[1]) * 1000) : 0,
      channels: fmt ? Number(fmt[1]) : 2,
      sampleRate: fmt ? Number(fmt[2]) : 44100,
      bitrate: br ? Number(br[1]) : 0,
    }
  } catch {
    return { durationMs: 0, channels: 2, sampleRate: 44100, bitrate: 0 }
  }
}

// AppleDouble sidecars (._*) are not audio — exclude them.
const files = fs
  .readdirSync(audioDir)
  .filter((f) => /\.mp3$/i.test(f) && !f.startsWith('._'))
  .sort()

const tracks = files.map((f, i) => {
  const full = path.join(audioDir, f)
  const { durationMs, channels, sampleRate, bitrate } = probe(full)
  const hash = crypto
    .createHash('sha256')
    .update(fs.readFileSync(full))
    .digest('hex')
    .slice(0, 16)
  const title = cleanTitle(f)
  return {
    id: `trk_${String(i + 1).padStart(2, '0')}`,
    trackNo: i + 1,
    title,
    isInterlude: /\(skit\)/i.test(f),
    hash,
    bytes: fs.statSync(full).size,
    durationMs,
    channels,
    sampleRate,
    bitrate,
    url: `/media/audio/${encodeURIComponent(f)}`,
  }
})

const totalMs = tracks.reduce((a, t) => a + t.durationMs, 0)
const banner = `// AUTO-GENERATED by scripts/gen-fixtures.mjs — do not edit by hand.
// Source: ./Bronze (gitignored, unmastered rough mixes).
// Regenerate: npm run fixtures
`

const body = `${banner}
import type { Release } from '@/content/types'

export const bronze: Release = {
  id: 'rel_bronze',
  artistSlug: 'dean',
  slug: 'bronze',
  title: 'Bronze',
  artistName: 'Dean',
  published: false,
  totalDurationMs: ${totalMs},
  tracks: ${JSON.stringify(tracks, null, 2).replace(/\n/g, '\n  ')},
}
`

fs.mkdirSync(path.dirname(outFile), { recursive: true })
fs.writeFileSync(outFile, body)
console.log(`✓ ${tracks.length} tracks → ${path.relative(root, outFile)}`)
console.log(`  total runtime ${Math.floor(totalMs / 60000)}m ${Math.round((totalMs % 60000) / 1000)}s`)
